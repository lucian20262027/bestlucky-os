'use client';

import React, { useEffect, useRef } from 'react';
import { Bold, Eraser, Highlighter, Italic } from 'lucide-react';

interface RichAnswerEditorProps {
  htmlValue?: string;
  textValue: string;
  placeholder?: string;
  minHeightClass?: string;
  onChange: (next: { html: string; text: string }) => void;
}

const FONT_OPTIONS = [
  { label: '默认无衬线 (Inter)', value: 'Inter, system-ui, sans-serif' },
  { label: '优雅衬线 (Georgia)', value: 'Georgia, serif' },
  { label: '苹果苹方 (PingFang)', value: '"PingFang SC", sans-serif' },
  { label: '代码等宽 (Mono)', value: '"JetBrains Mono", monospace' },
];

const SIZE_OPTIONS = [
  { label: '小', size: '13px', execSize: '2' },
  { label: '中', size: '15px', execSize: '3' },
  { label: '大', size: '18px', execSize: '4' },
  { label: '特大', size: '22px', execSize: '5' },
];

const COLOR_SWATCHES = [
  { label: '经典黑', color: '#111118' },
  { label: '主题紫', color: '#6E32F5' },
  { label: '深海蓝', color: '#2563EB' },
  { label: '翡翠绿', color: '#059669' },
  { label: '玫瑰红', color: '#E11D48' },
  { label: '琥珀橙', color: '#D97706' },
];

function plainTextToHtml(text: string): string {
  if (!text) return '';
  return text
    .split('\n')
    .map((line) => {
      const escaped = line
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;');
      return escaped ? `<p>${escaped}</p>` : '<p><br></p>';
    })
    .join('');
}

export function RichAnswerEditor({
  htmlValue,
  textValue,
  placeholder,
  minHeightClass = 'min-h-[340px]',
  onChange,
}: RichAnswerEditorProps) {
  const editorRef = useRef<HTMLDivElement | null>(null);
  const lastHtmlRef = useRef<string>('');

  const resolvedInitialHtml = htmlValue?.trim()
    ? htmlValue
    : plainTextToHtml(textValue);

  useEffect(() => {
    const el = editorRef.current;
    if (!el) return;
    if (el.innerHTML !== resolvedInitialHtml && lastHtmlRef.current !== resolvedInitialHtml) {
      el.innerHTML = resolvedInitialHtml;
      lastHtmlRef.current = resolvedInitialHtml;
    }
  }, [resolvedInitialHtml]);

  const emitUpdate = () => {
    const el = editorRef.current;
    if (!el) return;
    const html = el.innerHTML;
    const text = (el.innerText ?? '').replace(/\n{3,}/g, '\n\n').trim();
    lastHtmlRef.current = html;
    onChange({ html, text });
  };

  const applyCommand = (command: string, value?: string) => {
    editorRef.current?.focus();
    document.execCommand(command, false, value);
    emitUpdate();
  };

  const applyFontSizePx = (px: string, execSize: string) => {
    editorRef.current?.focus();
    document.execCommand('fontSize', false, execSize);
    // Replace legacy <font size="N"> tags generated by execCommand with exact px spans
    const el = editorRef.current;
    if (el) {
      el.querySelectorAll(`font[size="${execSize}"]`).forEach((node) => {
        const span = document.createElement('span');
        span.style.fontSize = px;
        span.innerHTML = node.innerHTML;
        node.replaceWith(span);
      });
    }
    emitUpdate();
  };

  return (
    <div className="overflow-hidden rounded-xl border border-[#ECECF2] bg-white focus-within:border-[#6E32F5]">
      {/* Rich Selection Toolbar */}
      <div
        className="flex flex-wrap items-center gap-1.5 border-b border-[#ECECF2] bg-[#FAFAFC] px-3 py-2"
        data-testid="rich-answer-toolbar"
      >
        <select
          aria-label="选中文字字体"
          defaultValue=""
          onChange={(e) => {
            if (!e.target.value) return;
            applyCommand('fontName', e.target.value);
            e.target.value = '';
          }}
          className="rounded-lg border border-[#ECECF2] bg-white px-2 py-1 text-[11px] font-medium text-[#111118] focus:border-[#6E32F5] focus:outline-none"
          data-testid="rich-font-select"
        >
          <option value="" disabled>
            选中字体...
          </option>
          {FONT_OPTIONS.map((f) => (
            <option key={f.label} value={f.value}>
              {f.label}
            </option>
          ))}
        </select>

        <div className="flex items-center gap-0.5 rounded-lg border border-[#ECECF2] bg-white p-0.5">
          {SIZE_OPTIONS.map((s) => (
            <button
              key={s.label}
              type="button"
              onMouseDown={(e) => {
                e.preventDefault();
                applyFontSizePx(s.size, s.execSize);
              }}
              data-testid={`rich-size-${s.size}`}
              className="rounded px-1.5 py-0.5 text-[11px] font-semibold text-[#525260] hover:bg-[#F3ECFF] hover:text-[#6E32F5]"
              title={`选中文字字号 ${s.size}`}
            >
              {s.label}
            </button>
          ))}
        </div>

        <div className="flex items-center gap-1 rounded-lg border border-[#ECECF2] bg-white px-1.5 py-1">
          {COLOR_SWATCHES.map((c) => (
            <button
              key={c.color}
              type="button"
              onMouseDown={(e) => {
                e.preventDefault();
                applyCommand('foreColor', c.color);
              }}
              data-testid={`rich-color-${c.color.slice(1)}`}
              className="h-4 w-4 rounded-full border border-black/15 transition hover:scale-110"
              style={{ backgroundColor: c.color }}
              title={`选中文字颜色: ${c.label}`}
            />
          ))}
        </div>

        <button
          type="button"
          onMouseDown={(e) => {
            e.preventDefault();
            applyCommand('hiliteColor', '#FEF08A');
          }}
          className="inline-flex items-center gap-1 rounded-lg border border-[#ECECF2] bg-white px-2 py-1 text-[11px] font-semibold text-[#525260] hover:border-amber-300 hover:bg-amber-50"
          title="黄色荧光高亮选中文字"
        >
          <Highlighter className="h-3 w-3 text-amber-500" />
          高亮
        </button>

        <button
          type="button"
          onMouseDown={(e) => {
            e.preventDefault();
            applyCommand('bold');
          }}
          className="rounded-lg border border-[#ECECF2] bg-white p-1.5 text-[#525260] hover:border-[#6E32F5] hover:text-[#6E32F5]"
          title="加粗"
        >
          <Bold className="h-3 w-3" />
        </button>

        <button
          type="button"
          onMouseDown={(e) => {
            e.preventDefault();
            applyCommand('italic');
          }}
          className="rounded-lg border border-[#ECECF2] bg-white p-1.5 text-[#525260] hover:border-[#6E32F5] hover:text-[#6E32F5]"
          title="斜体"
        >
          <Italic className="h-3 w-3" />
        </button>

        <button
          type="button"
          onMouseDown={(e) => {
            e.preventDefault();
            applyCommand('removeFormat');
          }}
          className="inline-flex items-center gap-1 rounded-lg border border-[#ECECF2] bg-white px-2 py-1 text-[11px] text-[#848494] hover:text-[#111118]"
          title="清除选中文字格式"
        >
          <Eraser className="h-3 w-3" />
          清除格式
        </button>
      </div>

      {/* ContentEditable Area */}
      <div
        ref={editorRef}
        contentEditable
        suppressContentEditableWarning
        onInput={emitUpdate}
        data-placeholder={placeholder}
        data-testid="rich-answer-editable"
        className={`${minHeightClass} w-full overflow-y-auto p-5 text-[15px] leading-relaxed text-[#111118] focus:outline-none [&>p]:mb-2.5`}
      />
    </div>
  );
}
